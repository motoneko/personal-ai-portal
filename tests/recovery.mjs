import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
const base=process.env.PORTAL_TEST_URL || 'http://127.0.0.1:8090';
const binary=process.env.PORTAL_TEST_BINARY || '/tmp/portal';
const ip='203.0.113.42';
execFileSync(binary,['security-ban',ip,'3600']);
const {token}=JSON.parse(execFileSync(binary,['security-recovery-token',ip],{encoding:'utf8'}));
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH,args:['--no-sandbox']});
const page=await browser.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/portal-login/recover/#'+token);
await page.locator('#confirm-recovery').waitFor();
assert.deepEqual(JSON.parse(execFileSync(binary,['security-recovery-jobs'],{encoding:'utf8'})),[]);
await page.locator('#confirm-recovery').click();
const jobs=JSON.parse(execFileSync(binary,['security-recovery-jobs'],{encoding:'utf8'}));
assert.equal(jobs.length,1);
const claim=JSON.parse(execFileSync(binary,['security-recovery-claim',jobs[0]],{encoding:'utf8'}));
assert.equal(claim.ip,ip);
execFileSync(binary,['security-recovery-apply',jobs[0]]);
execFileSync(binary,['security-recovery-finish',jobs[0]]);
await page.getByRole('status').filter({hasText:'已解除封禁'}).waitFor();
await page.reload();
await page.getByRole('status').filter({hasText:'已解除封禁'}).waitFor();
assert.equal(await page.locator('#confirm-recovery').count(),0);
assert.deepEqual(JSON.parse(execFileSync(binary,['security-recovery-jobs'],{encoding:'utf8'})),[]);
// A new ban after claim must survive an old queued recovery job.
execFileSync(binary,['security-ban',ip,'3600']);
const second=JSON.parse(execFileSync(binary,['security-recovery-token',ip],{encoding:'utf8'}));
await page.evaluate(async token=>fetch('/portal-api/recovery/redeem',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({token})}),second.token);
const nextJobs=JSON.parse(execFileSync(binary,['security-recovery-jobs'],{encoding:'utf8'}));
execFileSync(binary,['security-recovery-claim',nextJobs[0]]);
execFileSync(binary,['security-ban',ip,'7200']);
execFileSync(binary,['security-recovery-apply',nextJobs[0]]);
const stale=JSON.parse(execFileSync(binary,['security-recovery-finish',nextJobs[0]],{encoding:'utf8'}));
assert.equal(stale.status,'failed');
assert.ok(JSON.parse(execFileSync(binary,['security-recovery-token',ip],{encoding:'utf8'})).token);
execFileSync(binary,['security-unban',ip]);
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: unauthenticated recovery page, preview does not unlock, explicit confirmation, background completion, replay protection');
